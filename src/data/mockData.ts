export const INITIAL_ATTENDANCE: AttendanceRecord[] = INITIAL_STUDENTS.flatMap((st, idx) => {
  const today = new Date().toISOString().split('T')[0];
  const statuses: Array<'Hadir' | 'Sakit' | 'Izin' | 'Alpha'> = ['Hadir', 'Hadir', 'Hadir', 'Hadir', 'Hadir', idx === 2 ? 'Sakit' : idx === 5 ? 'Izin' : 'Hadir'];
  return [
    {
      id: `att-${st.id}-1`,
      studentId: st.id,
      date: today,
      status: statuses[idx % statuses.length],
    },
  ];
});

export const INITIAL_GRADES: GradeRecord[] = INITIAL_STUDENTS.flatMap((st) => {
  return INITIAL_SUBJECTS.map((sub, sIdx) => {
    const baseScore = 78 + ((st.nisn.charCodeAt(5) + sIdx) % 18);
    const formatif = Math.min(100, baseScore);
    const sumatif = Math.min(100, baseScore + 2);
    const avg = (formatif + sumatif) / 2;
    const predicate: 'A' | 'B' | 'C' | 'D' = avg >= 88 ? 'A' : avg >= 78 ? 'B' : avg >= 70 ? 'C' : 'D';
    return {
      id: `g-${st.id}-${sub.id}`,
      studentId: st.id,
      subjectId: sub.id,
      formatif,
      sumatif,
      tpDescription: `Menunjukkan penguasaan yang ${predicate === 'A' ? 'sangat baik' : 'baik'} pada kompetensi ${sub.name}.`,
      predicate,
    };
  });
});

